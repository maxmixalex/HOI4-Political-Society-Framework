"""Exact source reconstruction and position-aware native history diagnostics.

This does not allowlist a directory or an error code. A file earns a baseline
only if its complete generated bytes equal the reviewed bootstrap transform
of its independently verified original. Only diagnostics on unchanged source
lines with the same file/code/severity/message/context can be inherited.
"""
from __future__ import annotations

from collections import defaultdict, deque
from dataclasses import dataclass
import difflib
import hashlib
import json
from pathlib import Path, PurePosixPath
import sys

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))
from psf import bootstrap


def digest(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def normalized_original(raw: bytes) -> str:
    """Only the same explicit BOM/NOR source repairs used by the compiler."""
    text = raw.decode("utf-8").removeprefix("\ufeff")
    if digest(raw) in bootstrap.KNOWN_MISSING_FINAL_BRACE:
        if text.count(bootstrap.KNOWN_EMPTY_BRANCH) != 1:
            raise ValueError("Pinned Norway source no longer matches its explicit repair")
        text = text.replace(bootstrap.KNOWN_EMPTY_BRANCH, bootstrap.EMPTY_BRANCH_REPAIR, 1) + bootstrap.REPAIR
    return text


def equal_line_map(before: str, after: str) -> dict[int, int]:
    """Map 1-based after lines only where the complete original line survives."""
    first, second = before.splitlines(), after.splitlines()
    result = {}
    matcher = difflib.SequenceMatcher(a=first, b=second, autojunk=False)
    for tag, a, end_a, b, _ in matcher.get_opcodes():
        if tag == "equal":
            result.update({b + offset + 1: a + offset + 1 for offset in range(end_a - a)})
    return result


@dataclass
class NativeHistory:
    path: str
    original_sha256: str
    original: str
    baseline: str
    generated: bytes
    generated_to_baseline: dict[int, int]
    baseline_to_original: dict[int, int]


def reconstruct(relative: str, raw: bytes, generated: bytes) -> NativeHistory:
    expected, _ = bootstrap.patch_history(raw.decode("utf-8"))
    if generated != expected.encode("utf-8"):
        raise ValueError(f"Native history is not the exact source + bootstrap.patch_history output: {relative}")
    baseline = normalized_original(raw)
    original = raw.decode("utf-8").removeprefix("\ufeff")
    return NativeHistory(relative, digest(raw), original, baseline, generated,
                         equal_line_map(baseline, expected), equal_line_map(original, baseline))


def prepare(staged: Path, build_root: Path, vanilla: Path | None = None) -> dict[str, NativeHistory]:
    """Verify every original and generated byte before allowing any baseline."""
    report = json.loads((build_root / "build-manifest.json").read_text(encoding="utf-8"))
    metadata = report.get("bootstrap", {})
    if not metadata.get("enabled"):
        return {}
    records = {item["file"]: item for item in metadata["files"]}
    actual = {path.relative_to(staged).as_posix() for path in (staged / "history/countries").rglob("*.txt")}
    if set(records) != actual or len(records) != len(metadata["files"]):
        raise ValueError("Native history output filenames differ from the compiler's source inventory")
    if metadata.get("source_kind") == "bundled_user_supplied_snapshot":
        pins = json.loads((HERE / "native-history-imports.json").read_text(encoding="utf-8"))
        if set(records) != set(pins["files"]):
            raise ValueError("Bundled native history inventory differs from its pinned source snapshot")
        source_root = bootstrap.ASSETS
        expected_hashes = pins["files"]
    elif metadata.get("source_kind") == "explicit_game_snapshot" and vanilla:
        # The supplied installation is an independent source, not a generated
        # file accepted as its own baseline. Its hashes must match compilation.
        source_root = vanilla / "history/countries"
        expected_hashes = {path: item["sha256"] for path, item in records.items()}
    else:
        raise ValueError("Native history baseline requires the pinned bundle or the original --vanilla installation")
    verified = {}
    combined = hashlib.sha256()
    for relative in sorted(records):
        path = PurePosixPath(relative)
        if path.parts[:2] != ("history", "countries") or len(path.parts) != 3 or path.suffix != ".txt":
            raise ValueError(f"Invalid native history source path: {relative}")
        raw = (source_root / path.name).read_bytes()
        source_hash = digest(raw)
        if source_hash != expected_hashes[relative] or source_hash != records[relative]["sha256"]:
            raise ValueError(f"Original native history hash mismatch: {relative}")
        combined.update(path.name.encode("utf-8") + b"\0" + raw)
        generated = (staged / relative).read_bytes()
        verified[relative] = reconstruct(relative, raw, generated)
    if combined.hexdigest() != metadata["source_sha256"]:
        raise ValueError("Combined native history source hash differs from the compiled inventory")
    return verified


def relative_path(diagnostic: dict, staged: Path) -> str | None:
    try:
        return Path(diagnostic.get("file", "")).relative_to(staged).as_posix()
    except ValueError:
        return None


def context(history: NativeHistory, baseline_line: int) -> tuple[int, str] | None:
    original_line = history.baseline_to_original.get(baseline_line)
    if original_line is None:
        return None
    original = history.original.splitlines()
    baseline = history.baseline.splitlines()
    if original[original_line - 1] != baseline[baseline_line - 1]:
        return None
    # The complete original statement line and neighboring original lines are
    # part of the match; a repeated message elsewhere in the file is not enough.
    surrounding = "\n".join(original[max(0, original_line - 3):original_line + 2])
    return original_line, digest(surrounding.encode("utf-8"))


def classify(diagnostics: list[dict], baseline_diagnostics: list[dict], staged: Path,
             verified: dict[str, NativeHistory]) -> tuple[list[dict], list[dict]]:
    """Match raw diagnostics one-for-one, with independently mapped source lines."""
    candidates = defaultdict(deque)
    for diagnostic in baseline_diagnostics:
        path = relative_path(diagnostic, staged)
        if path not in verified or not isinstance(diagnostic.get("line"), int):
            continue
        original = context(verified[path], diagnostic["line"])
        if original:
            key = (path, diagnostic.get("code"), diagnostic.get("severity"), diagnostic.get("message"), *original)
            candidates[key].append(diagnostic)
    checked, inherited = [], []
    for diagnostic in diagnostics:
        path = relative_path(diagnostic, staged)
        history = verified.get(path)
        line = history.generated_to_baseline.get(diagnostic.get("line")) if history else None
        original = context(history, line) if line is not None else None
        key = (path, diagnostic.get("code"), diagnostic.get("severity"), diagnostic.get("message"), *original) if original else None
        if key and candidates[key]:
            inherited.append({"diagnostic": diagnostic, "baseline_diagnostic": candidates[key].popleft(),
                              "source": path, "source_sha256": history.original_sha256,
                              "source_line": original[0], "source_context_sha256": original[1],
                              "baseline_line": line})
        else:
            checked.append(diagnostic)
    return checked, inherited


def run_baseline(invoke, binary: Path, staged: Path, report: Path,
                 verified: dict[str, NativeHistory], vanilla: Path | None = None):
    """Swap only verified histories in the same complete staged environment."""
    try:
        for relative, history in verified.items():
            (staged / relative).write_bytes(history.baseline.encode("utf-8"))
        result, diagnostics = invoke(binary, staged, report, vanilla)
        if result not in (0, 1):
            raise ValueError(f"Native history baseline engine failed with unexpected exit {result}")
        return result, diagnostics
    finally:
        for relative, history in verified.items():
            (staged / relative).write_bytes(history.generated)
