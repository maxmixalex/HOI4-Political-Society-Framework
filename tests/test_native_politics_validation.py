"""Prove native diagnostics against unchanged, independently pinned sources."""
from __future__ import annotations

import copy
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from psf import native_rules
from psf.ui import gui_nodes
from tools.ci import native_history, native_politics


class NativePoliticsValidationTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.staged = self.root / "staged"
        self.build = self.root / "build"
        self.build.mkdir()
        self.metadata = native_rules.write(self.staged)
        self.write_metadata(self.metadata)

    def write_metadata(self, metadata):
        (self.build / "build-manifest.json").write_text(json.dumps({
            "native_mechanics": {"generic_adapters": metadata}}), encoding="utf-8")

    def diagnostic(self, relative, line, **changes):
        return {"file": str(self.staged / relative), "line": line,
                "code": "CW241", "severity": "Error",
                "message": "Unexpected value 'take_state' for peace_action_type", **changes}

    def test_supported_sources_match_independent_pins_and_complete_reconstruction(self):
        verified = native_politics.prepare(self.staged, self.build)
        self.assertEqual(set(verified), set(native_politics.PINS))
        for relative, history in verified.items():
            raw = (native_rules.ASSETS / relative).read_bytes()
            self.assertEqual(native_history.digest(raw), native_politics.PINS[relative])
            self.assertEqual(history.original_sha256, native_politics.PINS[relative])
            self.assertEqual(history.generated, (self.staged / relative).read_bytes())
            self.assertTrue(history.generated_to_baseline)

    def test_original_peace_error_matches_exact_line_and_diagnostic_once(self):
        verified = native_politics.prepare(self.staged, self.build)
        relative = native_rules.PEACE
        history = verified[relative]
        original_line = next(i for i, text in enumerate(history.original.splitlines(), 1)
                             if text.strip() == "peace_action_type = take_state")
        generated_line = next(new for new, old in history.generated_to_baseline.items()
                              if old == original_line)
        baseline = self.diagnostic(relative, original_line)
        actual = self.diagnostic(relative, generated_line)
        checked, inherited = native_history.classify([actual], [baseline], self.staged, verified)
        self.assertEqual(checked, [])
        self.assertEqual(len(inherited), 1)
        self.assertEqual(inherited[0]["source_line"], original_line)
        self.assertEqual(inherited[0]["source_sha256"], native_politics.PINS[relative])
        self.assertEqual(len(inherited[0]["source_context_sha256"]), 64)
        for changes in ({"code": "CW263"}, {"severity": "Warning"},
                        {"message": "New political adapter failure"},
                        {"line": generated_line + 1},
                        {"file": str(self.staged / "common/peace_conference/cost_modifiers/unknown.txt")}):
            altered = {**actual, **changes}
            checked, inherited = native_history.classify([altered], [baseline], self.staged, verified)
            self.assertEqual(checked, [altered])
            self.assertEqual(inherited, [])
        checked, inherited = native_history.classify([actual, actual], [baseline], self.staged, verified)
        self.assertEqual(checked, [actual])
        self.assertEqual(len(inherited), 1)

    def test_modified_fields_and_unchanged_lines_in_rewritten_blocks_cannot_be_inherited(self):
        verified = native_politics.prepare(self.staged, self.build)
        for relative, history in verified.items():
            text = history.generated.decode()
            changed = set(self.metadata["sources"][relative]["changed_definitions"])
            nodes = [node for node in gui_nodes(text)
                     if node.kind in changed and (node.parent is None or node.parent.parent is None)]
            self.assertEqual({node.kind for node in nodes}, changed)
            for node in nodes:
                first = text.count("\n", 0, node.start) + 1
                last = text.count("\n", 0, node.end - 1) + 1
                for line in range(first, last + 1):
                    self.assertNotIn(line, history.generated_to_baseline)
                    diagnostic = self.diagnostic(relative, line)
                    # Even identical file/message/line is insufficient for a
                    # block whose semantics are now generated by PSF.
                    checked, inherited = native_history.classify(
                        [diagnostic], [diagnostic], self.staged, verified)
                    self.assertEqual(checked, [diagnostic])
                    self.assertEqual(inherited, [])

    def test_generated_field_edits_unrelated_native_edits_and_additions_fail_reconstruction(self):
        relative = native_rules.PEACE
        raw = (native_rules.ASSETS / relative).read_bytes()
        generated = (self.staged / relative).read_bytes()
        for before, after in ((b"enable = { always = no }", b"enable = { always = yes }"),
                              (b"cost_multiplier = 1.0", b"cost_multiplier = 1.5"),
                              (b"cost_multiplier = 0.25", b"cost_multiplier = 0.27")):
            self.assertIn(before, generated)
            tampered = generated.replace(before, after, 1)
            with self.assertRaisesRegex(ValueError, "exact source"):
                native_politics.reconstruct(relative, raw, tampered)
        with self.assertRaisesRegex(ValueError, "exact source"):
            native_politics.reconstruct(relative, raw, generated + b"\npsf_unknown_field = yes\n")
        with self.assertRaisesRegex(ValueError, "Unsupported native politics baseline path"):
            native_politics.reconstruct("common/peace_conference/cost_modifiers/unknown.txt", raw, generated)

    def test_generated_metadata_cannot_bless_a_changed_bundled_source(self):
        copied = self.root / "source"
        for relative in native_politics.PINS:
            target = copied / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes((native_rules.ASSETS / relative).read_bytes())
        target = copied / native_rules.OPINIONS
        target.write_bytes(target.read_bytes() + b"\n# modified source, newly blessed by build metadata\n")
        with patch.object(native_rules, "ASSETS", copied):
            self.write_metadata(native_rules.write(self.staged))
            with self.assertRaisesRegex(ValueError, "Original native politics hash mismatch"):
                native_politics.prepare(self.staged, self.build)

    def test_inventories_hashes_and_changed_definition_records_fail_closed(self):
        candidates = []
        missing = copy.deepcopy(self.metadata)
        missing["sources"].pop(native_rules.OPINIONS)
        candidates.append((missing, "inventory"))
        unknown = copy.deepcopy(self.metadata)
        unknown["sources"]["common/opinion_modifiers/unknown.txt"] = unknown["sources"].pop(native_rules.OPINIONS)
        candidates.append((unknown, "inventory"))
        changed_files = copy.deepcopy(self.metadata)
        changed_files["files"] = [native_rules.OPINIONS]
        candidates.append((changed_files, "inventory"))
        tampered_hash = copy.deepcopy(self.metadata)
        tampered_hash["sources"][native_rules.OPINIONS]["source_sha256"] = "0" * 64
        candidates.append((tampered_hash, "hash mismatch"))
        changed_records = copy.deepcopy(self.metadata)
        changed_records["sources"][native_rules.OPINIONS]["changed_definitions"] = ["invented_definition"]
        candidates.append((changed_records, "changed-definition inventory"))
        unknown_origin = copy.deepcopy(self.metadata)
        unknown_origin["origin"] = "unverified_source"
        candidates.append((unknown_origin, "pinned bundle or original"))
        for metadata, message in candidates:
            with self.subTest(message=message):
                self.write_metadata(metadata)
                with self.assertRaisesRegex(ValueError, message):
                    native_politics.prepare(self.staged, self.build)

    def test_external_snapshot_must_be_present_and_match_compilation(self):
        original = self.root / "external"
        for relative in native_politics.PINS:
            target = original / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes((native_rules.ASSETS / relative).read_bytes())
        self.write_metadata(native_rules.write(self.staged, original))
        with self.assertRaisesRegex(ValueError, "pinned bundle or original"):
            native_politics.prepare(self.staged, self.build)
        self.assertEqual(set(native_politics.prepare(self.staged, self.build, original)), set(native_politics.PINS))
        target = original / native_rules.PEACE
        target.write_bytes(target.read_bytes() + b"\n# changed since compile\n")
        with self.assertRaisesRegex(ValueError, "hash mismatch"):
            native_politics.prepare(self.staged, self.build, original)

    def test_baseline_preserves_other_staged_files_and_restores_overrides_after_failure(self):
        verified = native_politics.prepare(self.staged, self.build)
        sentinel = self.staged / "common/scripted_effects/psf.txt"
        sentinel.parent.mkdir(parents=True)
        sentinel.write_text("psf_unchanged = { add_political_power = 1 }\n")
        before = sentinel.read_bytes()
        def failed_engine(binary, staged, report, vanilla):
            for relative, history in verified.items():
                self.assertEqual((staged / relative).read_bytes(), history.baseline.encode())
            self.assertEqual(sentinel.read_bytes(), before)
            raise RuntimeError("engine failure")
        with self.assertRaisesRegex(RuntimeError, "engine failure"):
            native_history.run_baseline(failed_engine, Path("engine"), self.staged,
                                        self.root / "baseline.json", verified)
        for relative, history in verified.items():
            self.assertEqual((self.staged / relative).read_bytes(), history.generated)
        self.assertEqual(sentinel.read_bytes(), before)


if __name__ == "__main__":
    unittest.main()
